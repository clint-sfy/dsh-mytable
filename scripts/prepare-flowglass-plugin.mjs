import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'node_modules', 'dsh-flowglass', 'flowglass', 'lib', 'client.js')
const bundledTargetPath = join(root, 'src', 'client', 'flowglass-bundled.generated.js')

const upstreamSource = await readFile(sourcePath, 'utf8')
// dsh-mytable 内嵌版只允许作为工作台窗口存在。不要根据运行时 marker 决定，
// 否则启动竞态会重新注册 Harness / Better Sidebar 的侧栏入口。
let source = upstreamSource.replace(
  /const worktableOnly = RT\.bundleId === 'flow'\s*&& typeof window !== 'undefined'\s*&& window\.__dshMytable\s*&& typeof window\.__dshMytable\.registerPaneType === 'function'/,
  "const worktableOnly = RT.bundleId === 'flow'",
)
if (source === upstreamSource) throw new Error('Flowglass worktable-only guard was not found')

// 窗口类型会在 Remote 挂载前注册，因此用户可能在连接完成前打开流镜。
// 上游默认 `host = null`，这会让首个 effect 的 host.call 直接抛 TypeError。
// 先放一个会明确拒绝的连接中 facade；轮询会在真实 host 就绪后自动恢复。
source = source.replace(
  '    let host = null',
  `    let host = {
      call(methodName, args) {
        return Promise.reject(new Error('Flowglass 服务正在连接'))
      },
    }`,
)
if (source.includes('    let host = null')) throw new Error('Flowglass null host facade was not replaced')

const pluginApplyBlock = `      const plugins = [createToolboxClient(), ].filter(Boolean)
      for (const plugin of plugins) {
        if (!plugin || typeof plugin.apply !== 'function') throw new Error('静态 Client feature 未返回有效插件对象')
        const disposer = await plugin.apply(ctx)
        if (typeof disposer === 'function') ctx.effect(() => disposer)
      }
`
const remoteMountMarker = '      const disposeRemote = await ctx.remote.$mount(remoteContribution)\n'
if (!source.includes(pluginApplyBlock) || !source.includes(remoteMountMarker)) {
  throw new Error('Flowglass client startup blocks were not found')
}
// 工作台窗口注册不应被 Remote 初始化阻塞。先注册 pane，再连接数据服务；
// 后台稍晚就绪时窗口仍然存在，打开后即可使用同一 host facade。
source = source.replace(pluginApplyBlock, '')
source = source.replace(remoteMountMarker, pluginApplyBlock + remoteMountMarker)
if (!source.includes('registerPaneType') || !source.includes('dsh-flowglass:flow')) {
  throw new Error('Flowglass worktable registration is missing')
}

const factoryMarker = 'factory: (require) => {'
const factoryStart = source.indexOf(factoryMarker)
const factoryEnd = source.lastIndexOf('\n  },\n})')
if (factoryStart < 0 || factoryEnd <= factoryStart) {
  throw new Error('Flowglass client factory could not be extracted')
}
const factoryBody = source.slice(factoryStart + factoryMarker.length, factoryEnd)
const bundledClient = [
  '// Generated by scripts/prepare-flowglass-plugin.mjs. Do not edit.',
  'export function createBundledFlowglassClient(require) {',
  factoryBody,
  '}',
  '',
].join('\n')
await writeFile(bundledTargetPath, bundledClient, 'utf8')
